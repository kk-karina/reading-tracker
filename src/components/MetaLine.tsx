import { Children, isValidElement, type ReactNode } from 'react'

/**
 * Подпись через точку: «▪ Поток · вчера · Изменить», «⟲ Практика · В работе».
 *
 * Одна на все места, где сущности перечисляют в строку: шапка листа
 * конспекта, строка под названием материала, подпись карточки. Раньше каждая
 * собирала её сама — то `join(' · ')` с пробелами, то отдельным элементом с
 * зазором, — и расстояния расходились: в моноширинной шапке точка стояла в
 * пробеле, а значок отходил от слова дальше, чем слово от соседа.
 *
 * Правило расстояний одно: значок прижат к своему слову (`--meta-lead`),
 * а сущности разведены шире — по `--meta-sep` с каждой стороны точки. Так
 * видно, что с чем связано.
 *
 * Точка — часть следующей сущности, а не отдельный элемент: при переносе она
 * уезжает вместе со словом, а не повисает в конце строки. Точку, оказавшуюся
 * в начале строки, срезает левый край — см. `.meta-line` в index.css.
 *
 * Типографику строка не задаёт. Подпись к заголовку — шапка листа
 * конспекта, строка под названием материала — набирается `label`, одним
 * шрифтом. Подпись карточки в списке — мелким обычным: заглавные в каждой
 * строке списка перекрикивали бы названия.
 */
export function MetaLine({
  lead,
  children,
  className,
}: {
  /** Значок или точка цвета перед первой сущностью. */
  lead?: ReactNode
  /** Сущности по порядку; пустые пропускаются. */
  children: ReactNode
  className?: string
}) {
  // `toArray` уже выбросил null, false и undefined — остаётся пустая строка.
  const items = Children.toArray(children).filter((c) => c !== '')
  return (
    <span className={`meta-line${className ? ` ${className}` : ''}`}>
      <span className="meta-line-row">
        {items.map((item, i) => (
          <span key={isValidElement(item) && item.key != null ? item.key : i} className="meta-line-item">
            {i === 0 && lead}
            {item}
          </span>
        ))}
      </span>
    </span>
  )
}
