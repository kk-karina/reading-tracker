/**
 * Ссылка это или название.
 *
 * От ответа зависит, куда уйдёт строка захвата: ссылку читает ✦, название
 * ищется в Open Library. Ошибка здесь стоит дорого в одну сторону — название,
 * принятое за ссылку, уходит стороннему сервису впустую, — поэтому ссылкой
 * считается только то, в чём нет пробелов и есть домен с буквенной зоной.
 * Кириллица в домене не поддержана намеренно: «Ф.М.Достоевский» иначе
 * становится сайтом.
 */
const SCHEME = /^https?:\/\/\S+$/i
const BARE = /^[a-z0-9-]+(\.[a-z0-9-]+)*\.[a-z]{2,}(?:[/?#:]\S*)?$/i

export function looksLikeUrl(raw: string): boolean {
  const s = raw.trim()
  if (!s || /\s/.test(s)) return false
  return SCHEME.test(s) || BARE.test(s)
}
