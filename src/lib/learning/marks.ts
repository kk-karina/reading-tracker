/**
 * Цвета маркера.
 *
 * Лимон — главный и без имени: `==…==` остаётся тем, чем был, и всё, что уже
 * отмечено в конспектах, не меняется. Остальные цвета пишутся именем в фигурных
 * скобках сразу после открывающих знаков: `=={pink}…==`. В чужом редакторе это
 * выродится в обычный маркер с видимым словом в начале — текст не потеряется.
 *
 * Здесь только имена. Сами цвета живут в CSS (`--mark-*`): поле правки читает
 * их оттуда, и у палитры один источник.
 */
export const MARK_COLORS = ['lemon', 'pink', 'peach', 'mint', 'sky'] as const

export type MarkColor = (typeof MARK_COLORS)[number]

/** Имя цвета в разметке. Лимон имени не носит — он маркер по умолчанию. */
const NAMED = MARK_COLORS.filter((c) => c !== 'lemon').join('|')

/**
 * Маркер в строке: 1 — имя цвета (или пусто для лимона), 2 — текст.
 * Не через строку: маркер, как и в руке, тянется по одной строке.
 */
export const MARK = new RegExp(`==(?:\\{(${NAMED})\\})?([^\\n]+?)==`, 'g')

export const isMarkColor = (s: string | null | undefined): s is MarkColor =>
  !!s && (MARK_COLORS as readonly string[]).includes(s)

/** Знаки, которыми цвет открывается в markdown. */
export const markOpen = (c: MarkColor) => (c === 'lemon' ? '==' : `=={${c}}`)
